'''FastAPI service that writes numbers in generated handwriting.'''

import logging
import secrets
import time
from collections.abc import AsyncIterator, Awaitable, Callable
from contextlib import asynccontextmanager
from typing import Annotated, Literal

from fastapi import FastAPI, HTTPException, Query, Request, Response
from fastapi.responses import RedirectResponse
from pydantic import BaseModel

from digitgan import __version__
from digitgan.checkpoints import GeneratorCheckpoint, load_checkpoint
from digitgan.config import AppConfig
from digitgan.generation import generate_number, png_bytes, render_grid

logger = logging.getLogger(__name__)

MAX_SEED = 2**31 - 1


class HealthResponse(BaseModel):
    '''Service status and the generator being served.'''

    status: Literal['ok', 'unavailable']
    version: str
    model_name: str | None = None
    training_seed: int | None = None


class _ServiceState:
    checkpoint: GeneratorCheckpoint | None = None


def create_app(config: AppConfig, checkpoint: GeneratorCheckpoint | None = None) -> FastAPI:
    '''Build the service.

    Args:
        config: Project configuration. The api section sets the checkpoint and request limits.
        checkpoint: Generator to serve. Loaded from config.api.checkpoint_path when omitted.

    Returns:
        The FastAPI application.
    '''
    settings = config.api
    state = _ServiceState()

    @asynccontextmanager
    async def lifespan(_: FastAPI) -> AsyncIterator[None]:
        state.checkpoint = checkpoint or _load_servable(config)
        yield

    app = FastAPI(
        title='digitgan',
        version=__version__,
        description='Writes any number in handwriting generated by a conditional GAN.',
        lifespan=lifespan,
    )

    @app.middleware('http')
    async def log_requests(
        request: Request, call_next: Callable[[Request], Awaitable[Response]]
    ) -> Response:
        started = time.perf_counter()
        response = await call_next(request)
        elapsed_ms = 1000 * (time.perf_counter() - started)
        logger.info(
            '%s %s %d %.1f ms', request.method, request.url.path, response.status_code, elapsed_ms
        )
        return response

    @app.get('/', include_in_schema=False)
    def index() -> RedirectResponse:
        return RedirectResponse('/docs')

    @app.get('/health', responses={503: {'model': HealthResponse}})
    def health(response: Response) -> HealthResponse:
        '''Report whether a generator is loaded.'''
        if state.checkpoint is None:
            response.status_code = 503
            return HealthResponse(status='unavailable', version=__version__)
        return HealthResponse(
            status='ok',
            version=__version__,
            model_name=state.checkpoint.model_name,
            training_seed=state.checkpoint.seed,
        )

    @app.get(
        '/generate',
        response_class=Response,
        responses={
            200: {'content': {'image/png': {}}, 'description': 'The number as a PNG image.'},
            503: {'description': 'No generator is loaded.'},
        },
    )
    def generate(
        digits: Annotated[
            str,
            Query(
                pattern='^[0-9]+$',
                max_length=settings.max_digits,
                description='Digits to write, such as 2026.',
            ),
        ],
        variations: Annotated[
            int, Query(ge=1, le=settings.max_variations, description='Rows, one style each.')
        ] = 1,
        seed: Annotated[
            int | None, Query(ge=0, le=MAX_SEED, description='Noise seed. Random when omitted.')
        ] = None,
        scale: Annotated[
            int, Query(ge=1, le=settings.max_scale, description='Pixel enlargement factor.')
        ] = 4,
    ) -> Response:
        '''Write the digits once per variation and return the picture as a PNG.

        Each row reuses one noise vector, so its digits share a handwriting style. The seed
        used is returned in the X-Seed header, so a result can be reproduced.
        '''
        if state.checkpoint is None:
            raise HTTPException(status_code=503, detail='No generator is loaded')
        chosen_seed = seed if seed is not None else secrets.randbelow(MAX_SEED)
        images = generate_number(
            state.checkpoint.generator, [int(digit) for digit in digits], variations, chosen_seed
        )
        picture = png_bytes(render_grid(images, scale=scale))
        return Response(picture, media_type='image/png', headers={'X-Seed': str(chosen_seed)})

    return app


def _load_servable(config: AppConfig) -> GeneratorCheckpoint | None:
    '''Load the configured generator, or return None so that /health can report the problem.'''
    path = config.api.checkpoint_path
    try:
        checkpoint = load_checkpoint(path)
    except (FileNotFoundError, ValueError) as error:
        logger.error('%s', error)
        return None
    if not checkpoint.conditional:
        logger.error('%s is unconditional, so it cannot write chosen digits', path.as_posix())
        return None
    logger.info('Serving %s trained with seed %d', checkpoint.model_name, checkpoint.seed)
    return checkpoint
