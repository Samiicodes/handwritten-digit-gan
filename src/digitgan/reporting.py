'''The evaluation report in Markdown and the metrics as JSON.'''

import json
from collections.abc import Callable, Sequence
from dataclasses import asdict, dataclass
from pathlib import Path

from digitgan.checkpoints import GeneratorCheckpoint
from digitgan.config import AppConfig
from digitgan.evaluation import MetricSummary, SourceMetrics, SourceSummary

REPORT_FILE = 'evaluation_report.md'
METRICS_FILE = 'metrics.json'
FIGURE_DIR_NAME = 'figures'

Formatter = Callable[[float], str]


@dataclass(frozen=True)
class ReportData:
    '''Everything the report shows.'''

    config: AppConfig
    train_size: int
    test_size: int
    classifier_accuracy: float
    metrics: Sequence[SourceMetrics]
    summaries: Sequence[SourceSummary]
    checkpoints: Sequence[GeneratorCheckpoint]
    # Figure titles and paths relative to the report directory, in display order
    figures: Sequence[tuple[str, Path]]


def format_mse(value: float) -> str:
    '''Pixel MSE with three decimals.'''
    return f'{value:.3f}'


def format_fid(value: float) -> str:
    '''FID with two decimals.'''
    return f'{value:.2f}'


def format_rate(value: float) -> str:
    '''A share as a percentage with one decimal.'''
    return f'{100 * value:.1f}%'


def format_balance(value: float) -> str:
    '''Normalised entropy with three decimals.'''
    return f'{value:.3f}'


def format_summary(summary: MetricSummary | None, formatter: Formatter, seeds: int) -> str:
    '''Format a mean, adding the spread when it comes from more than one seed.'''
    if summary is None:
        return 'n/a'
    if seeds < 2:
        return formatter(summary.mean)
    # A percentage sign goes once, after the spread
    mean = formatter(summary.mean).removesuffix('%')
    return f'{mean} ± {formatter(summary.std)}'


def write_evaluation_report(data: ReportData, path: Path) -> Path:
    '''Write the Markdown report and return its path.'''
    sections = [
        _header(),
        _setup_section(data),
        _results_section(data),
        _metric_notes(data),
        _per_seed_section(data),
        _training_time_section(data),
        _figure_section(data),
    ]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text('\n\n'.join(sections) + '\n', encoding='utf-8', newline='\n')
    return path


def write_metrics_json(data: ReportData, path: Path) -> Path:
    '''Write per-seed metrics and summaries as JSON for other tools.'''
    payload = {
        'classifier_test_accuracy': data.classifier_accuracy,
        'sample_size': data.config.evaluation.sample_size,
        'pixel_mse_size': data.config.evaluation.pixel_mse_size,
        'summaries': [asdict(summary) for summary in data.summaries],
        'runs': [asdict(item) for item in data.metrics],
    }
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, indent=2) + '\n', encoding='utf-8', newline='\n')
    return path


def _header() -> str:
    return (
        '# Evaluation report\n\n'
        'Generated by `scripts/evaluate_models.py` from the saved training runs. '
        'Rerun the script rather than editing this file.'
    )


def _setup_section(data: ReportData) -> str:
    training = data.config.training
    evaluation = data.config.evaluation
    beta1, beta2 = training.adam_betas
    # Taken from the runs rather than the configuration, which may have changed since training
    epochs = sorted({len(checkpoint.history) for checkpoint in data.checkpoints})
    seeds = sorted({checkpoint.seed for checkpoint in data.checkpoints})
    rows = [
        ('Training images', f'{data.train_size:,} from the MNIST training split'),
        ('Test images', f'{data.test_size:,} from the MNIST test split'),
        ('Epochs', ', '.join(str(count) for count in epochs)),
        ('Batch size', str(training.batch_size)),
        ('Optimiser', f'Adam, learning rate {training.learning_rate}, betas {beta1} and {beta2}'),
        ('Noise dimension', str(training.latent_dim)),
        (
            'Discriminator target for real images',
            f'{training.real_label_target} (one-sided label smoothing)',
        ),
        ('Training seeds', ', '.join(str(seed) for seed in seeds)),
        (
            'Evaluation classifier',
            f'{format_rate(data.classifier_accuracy)} accuracy on the test split',
        ),
        ('Generated images per run', f'{evaluation.sample_size:,}, the same number of each digit'),
        ('Pixel MSE images', f'The first {evaluation.pixel_mse_size:,} test images'),
    ]
    lines = ['## Setup', '', '| Setting | Value |', '| --- | --- |']
    lines += [f'| {name} | {value} |' for name, value in rows]
    return '\n'.join(lines)


def _results_section(data: ReportData) -> str:
    lines = [
        '## Results',
        '',
        'GAN rows give the mean and standard deviation across training seeds. Real images and '
        'the baseline involve no training, so they have a single value.',
        '',
        '| Source | Runs | Pixel MSE | FID | Recognisable | Class balance | Correct digit |',
        '| --- | --- | --- | --- | --- | --- | --- |',
    ]
    for summary in data.summaries:
        runs = max(len(summary.seeds), 1)
        lines.append(
            f'| {summary.display_name} | {runs} '
            f'| {format_summary(summary.pixel_mse, format_mse, runs)} '
            f'| {format_summary(summary.fid, format_fid, runs)} '
            f'| {format_summary(summary.recognisable_rate, format_rate, runs)} '
            f'| {format_summary(summary.class_balance, format_balance, runs)} '
            f'| {format_summary(summary.correct_digit_rate, format_rate, runs)} |'
        )
    return '\n'.join(lines)


def _metric_notes(data: ReportData) -> str:
    evaluation = data.config.evaluation
    threshold = format_rate(evaluation.confidence_threshold).replace('.0%', '%')
    return '\n'.join(
        [
            'What each column measures:',
            '',
            '- **Pixel MSE** is the coursework metric: the mean squared pixel difference '
            'between one generated image and each of the first '
            f'{evaluation.pixel_mse_size:,} test images. Conditional sources are asked for the '
            'digit of the test image they are compared with, unconditional sources are not, so '
            'the two groups are only comparable within themselves. The real-image rows show '
            'what real handwriting scores.',
            '- **FID** is the Frechet distance between generated and test images in the feature '
            'space of the evaluation classifier. It rewards realism and variety together. It is '
            'not comparable with FID values computed with an Inception network.',
            '- **Recognisable** is the share of images that the classifier assigns to one digit '
            f'with a probability of at least {threshold}.',
            '- **Class balance** is the normalised entropy of the digits the classifier sees. A '
            'value of 1.0 means all ten digits appear equally often; lower values point to mode '
            'collapse.',
            '- **Correct digit** is the share of images classified as the digit that was '
            'requested. It applies only to sources that take a digit as input.',
        ]
    )


def _per_seed_section(data: ReportData) -> str:
    lines = [
        '## Results per run',
        '',
        '| Source | Seed | Pixel MSE | FID | Recognisable | Class balance | Correct digit |',
        '| --- | --- | --- | --- | --- | --- | --- |',
    ]
    for item in data.metrics:
        if item.seed is None:
            continue
        correct = 'n/a' if item.correct_digit_rate is None else format_rate(item.correct_digit_rate)
        lines.append(
            f'| {item.display_name} | {item.seed} | {format_mse(item.pixel_mse)} '
            f'| {format_fid(item.fid)} | {format_rate(item.recognisable_rate)} '
            f'| {format_balance(item.class_balance)} | {correct} |'
        )
    return '\n'.join(lines)


def _training_time_section(data: ReportData) -> str:
    lines = [
        '## Training time',
        '',
        'Wall-clock time per run, including the FID checks. Measured on the machine that '
        'produced this report.',
        '',
        '| Run | Epochs | Seconds per epoch | Total minutes |',
        '| --- | --- | --- | --- |',
    ]
    for checkpoint in data.checkpoints:
        seconds = sum(stats.seconds for stats in checkpoint.history)
        epochs = len(checkpoint.history)
        lines.append(
            f'| {checkpoint.display_name}, seed {checkpoint.seed} | {epochs} '
            f'| {seconds / epochs:.1f} | {seconds / 60:.1f} |'
        )
    return '\n'.join(lines)


def _figure_section(data: ReportData) -> str:
    lines = ['## Figures']
    for title, figure_path in data.figures:
        lines += ['', f'### {title}', '', f'![{title}]({figure_path.as_posix()})']
    return '\n'.join(lines)
